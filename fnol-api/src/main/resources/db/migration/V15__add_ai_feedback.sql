-- Adjuster feedback on the AI: one row per adjuster decision, next to what the AI said. Used to measure the AI
-- against adjusters (GET /api/v1/ai/metrics) and as new labelled data for the trust score.
CREATE TABLE ai_feedback (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id                   VARCHAR(32)    NOT NULL,
    line_of_business           VARCHAR(16),
    ai_damage_type             VARCHAR(40),
    adjuster_damage_type       VARCHAR(40),
    ai_status                  VARCHAR(40),
    adjuster_decision          VARCHAR(40)    NOT NULL,
    ai_reserve                 NUMERIC(14, 2),
    adjuster_reserve           NUMERIC(14, 2),
    ai_confidence              NUMERIC(6, 4),
    raw_confidence             NUMERIC(6, 4),
    probability_margin         NUMERIC(6, 4),
    second_opinion_agreement   NUMERIC(6, 4),
    photo_subject              VARCHAR(20),
    gate_flags                 VARCHAR(500),
    adjuster_id                VARCHAR(64),
    decided_at                 TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ai_feedback_claim ON ai_feedback (claim_id);
CREATE INDEX idx_ai_feedback_decided ON ai_feedback (decided_at);
