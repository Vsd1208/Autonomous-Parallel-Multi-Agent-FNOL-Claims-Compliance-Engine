-- Mock ClaimCenter storage, kept in its own schema so it stays separate from the FNOL tables.
-- Runs at every start (spring.sql.init.mode=always), so each statement must be idempotent.
CREATE SCHEMA IF NOT EXISTS claimcenter;

CREATE TABLE IF NOT EXISTS claimcenter.claims (
    claim_id         VARCHAR(32)    PRIMARY KEY,
    status           VARCHAR(40)    NOT NULL,
    policy_number    VARCHAR(64)    NOT NULL,
    incident_date    DATE,
    state            VARCHAR(8),
    estimated_damage NUMERIC(14, 2),
    reserve          NUMERIC(14, 2),
    notes            TEXT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS claimcenter.review_actions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id         VARCHAR(32)    NOT NULL REFERENCES claimcenter.claims (claim_id),
    acted_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    action           VARCHAR(40),
    status           VARCHAR(40),
    adjuster_id      VARCHAR(64),
    notes            TEXT,
    adjusted_reserve NUMERIC(14, 2)
);

CREATE TABLE IF NOT EXISTS claimcenter.attachments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id         VARCHAR(32)    NOT NULL REFERENCES claimcenter.claims (claim_id),
    name             VARCHAR(255)   NOT NULL,
    content_type     VARCHAR(100),
    body             TEXT,
    attached_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cc_review_actions_claim ON claimcenter.review_actions (claim_id);
CREATE INDEX IF NOT EXISTS idx_cc_attachments_claim ON claimcenter.attachments (claim_id);

-- Claim child objects, shaped after ClaimCenter's entities (Cloud API claim resources).
CREATE TABLE IF NOT EXISTS claimcenter.exposures (
    exposure_id      VARCHAR(40)    PRIMARY KEY,
    claim_id         VARCHAR(32)    NOT NULL REFERENCES claimcenter.claims (claim_id),
    exposure_type    VARCHAR(40),
    coverage_type    VARCHAR(40),
    reserve          NUMERIC(14, 2),
    cost_type        VARCHAR(40),
    status           VARCHAR(16)    NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS claimcenter.activities (
    activity_id      VARCHAR(40)    PRIMARY KEY,
    claim_id         VARCHAR(32)    NOT NULL REFERENCES claimcenter.claims (claim_id),
    subject          VARCHAR(255)   NOT NULL,
    description      TEXT,
    priority         VARCHAR(16),
    due_date         DATE,
    assigned_to      VARCHAR(64),
    status           VARCHAR(16)    NOT NULL,
    completed_by     VARCHAR(64),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS claimcenter.notes (
    note_id          VARCHAR(40)    PRIMARY KEY,
    claim_id         VARCHAR(32)    NOT NULL REFERENCES claimcenter.claims (claim_id),
    topic            VARCHAR(64),
    subject          VARCHAR(255),
    body             TEXT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cc_exposures_claim ON claimcenter.exposures (claim_id);
CREATE INDEX IF NOT EXISTS idx_cc_activities_claim ON claimcenter.activities (claim_id);
CREATE INDEX IF NOT EXISTS idx_cc_notes_claim ON claimcenter.notes (claim_id);

-- The FNOL as reported (the claims system is the system of record for the loss report: it holds the reporter's
-- details, as a claims system does; the AI extension reads it but stores no raw personal data).
CREATE TABLE IF NOT EXISTS claimcenter.fnol_reports (
    claim_id         VARCHAR(32)    PRIMARY KEY REFERENCES claimcenter.claims (claim_id),
    payload          TEXT           NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Event outbox: written in the same transaction as the change it reports, delivered to subscribers by
-- EventDispatcher with retries (at-least-once; subscribers de-duplicate by event_id).
CREATE TABLE IF NOT EXISTS claimcenter.events (
    event_id         VARCHAR(40)    PRIMARY KEY,
    event_type       VARCHAR(40)    NOT NULL,
    claim_id         VARCHAR(32)    NOT NULL,
    payload          TEXT           NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts         INT            NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at     TIMESTAMP WITH TIME ZONE,
    last_error       VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_cc_events_pending ON claimcenter.events (delivered_at, next_attempt_at);
